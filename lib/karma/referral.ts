/**
 * Награда за приглашённых.
 *
 * Модуль чистый и без зависимостей — те же правила считает Worker.
 *
 * Две выплаты пригласившему:
 *   1. разовый бонус, когда у приглашённого подтвердят ПЕРВОЕ дело;
 *   2. доля от каждого его подтверждённого дела.
 *
 * Почему бонус не за регистрацию: карма в V2 появляется только после чужой
 * оценки, иначе десяток пустых аккаунтов давал бы сотню баллов даром. Привязка
 * к первому подтверждённому делу оставляет за приглашённым живого человека и
 * живого проверяющего.
 */

/** Разовый бонус за приглашённого, дошедшего до первого подтверждения. */
export const REFERRAL_JOIN_BONUS = 10;

/** Доля от каждого подтверждённого дела приглашённого, в процентах. */
export const REFERRAL_SHARE_PERCENT = 1;

/**
 * Доля считается в сотых балла и копится.
 *
 * Дело стоит 5–50 карм, процент от него — от 0.05 до 0.5. При целочисленной
 * карме обычное округление обнулило бы долю навсегда: сколько бы дел ни сделал
 * приглашённый, пригласивший не получил бы ничего. Поэтому храним остаток
 * в сотых и переводим в карму, когда набирается целый балл.
 *
 * Сотые от процента — это ровно `finalScore * REFERRAL_SHARE_PERCENT`:
 * 1% от 25 = 0.25 балла = 25 сотых.
 */
export const HUNDREDTHS_PER_POINT = 100;

export interface ReferralPayout {
  /** Сколько кармы начислить пригласившему прямо сейчас. */
  karma: number;
  /** Что осталось в копилке сотых, 0..99. */
  fraction: number;
}

/**
 * Сколько получит пригласивший с одного подтверждённого дела.
 *
 * `fraction` — накопленный остаток пригласившего, `finalScore` — итог дела,
 * `joinBonusDue` — не выплачен ли ещё разовый бонус за этого приглашённого.
 */
export function referralPayout(
  fraction: number,
  finalScore: number,
  joinBonusDue: boolean,
): ReferralPayout {
  const pooled = fraction + finalScore * REFERRAL_SHARE_PERCENT;
  return {
    karma: Math.floor(pooled / HUNDREDTHS_PER_POINT) + (joinBonusDue ? REFERRAL_JOIN_BONUS : 0),
    fraction: pooled % HUNDREDTHS_PER_POINT,
  };
}
