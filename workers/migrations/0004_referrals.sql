-- Награда за приглашённых.
--
-- Пригласивший получает разовый бонус, когда у приглашённого подтвердят первое
-- дело, и долю от каждого его подтверждённого дела. Правила — в
-- lib/karma/referral.ts; здесь только места, где это хранится.

-- Кто пригласил. Ставится один раз, при переходе по ссылке ?startapp=f<id>.
ALTER TABLE users ADD COLUMN referred_by INTEGER REFERENCES users(id);

-- Отметка на приглашённом: разовый бонус за него уже выплачен. Живёт именно
-- здесь, а не у пригласившего, — так «один бонус за одного человека»
-- проверяется одной строкой, без отдельной таблицы выплат.
ALTER TABLE users ADD COLUMN referral_bonus_paid_at TEXT;

-- Сколько кармы пришло от приглашённых. Входит в karma_total, отдельной
-- шкалы больше не заводим — вторую уже убирали как путающую. Нужна, чтобы
-- инвариант «карма = сумма подтверждённых дел» остался проверяемым:
-- теперь он звучит как «карма = дела + приглашённые».
ALTER TABLE users ADD COLUMN karma_referral INTEGER NOT NULL DEFAULT 0;

-- Копилка сотых балла, 0..99. Процент от дела меньше единицы, и без остатка
-- доля обнулялась бы на каждом начислении.
ALTER TABLE users ADD COLUMN referral_fraction INTEGER NOT NULL DEFAULT 0;

CREATE INDEX idx_users_referred_by ON users(referred_by);
