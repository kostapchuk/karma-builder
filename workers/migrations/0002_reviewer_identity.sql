-- Оценка перестаёт быть анонимной.
--
-- Страница рецензента открывалась в любом браузере без логина, и сервер не знал,
-- кто поставил балл. Из этого следовало главное: автор мог открыть собственную
-- ссылку и подтвердить своё же дело — вся проверка держалась на честном слове.
-- Теперь ревью идёт через Mini App, у рецензента есть telegram_id, и мы его
-- храним.
ALTER TABLE reviews ADD COLUMN reviewer_user_id INTEGER REFERENCES users(id);

-- Один человек — одна оценка на дело. NULL в SQLite не равен NULL, поэтому
-- уже накопленные анонимные строки индекс не ломают и между собой не конфликтуют.
CREATE UNIQUE INDEX idx_reviews_deed_reviewer ON reviews(deed_id, reviewer_user_id);
